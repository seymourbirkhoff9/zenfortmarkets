def normalize_language(code: Optional[str]) -> str:
    """Normalize language code to a supported key, defaulting to 'en'."""
    if not code:
        return "en"
    clean = code.strip()
    if clean in SUPPORTED_LANGUAGES:
        return clean
    # Check 2-letter prefix, e.g. "es-MX" -> "es"
    prefix = clean.split("-")[0].lower()
    if prefix in SUPPORTED_LANGUAGES:
        return prefix
    return "en"


def get_string(key: str, lang: str = "en", **kwargs) -> str:
    """Retrieve translated string with automatic fallback to English."""
    norm = normalize_language(lang)
    lang_dict = TRANSLATIONS.get(norm, TRANSLATIONS["en"])
    val = lang_dict.get(key) or TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val


@lru_cache(maxsize=2048)
def auto_translate_text(text: str, target_lang: str = "en") -> str:
    """Translate dynamic or custom text using Google's free endpoint with graceful fallback."""
    if not text or not target_lang or target_lang == "en":
        return text
    norm = normalize_language(target_lang)
    if norm == "en":
        return text
    try:
        url = "https://translate.googleapis.com/translate_a/single?" + urllib.parse.urlencode({
            "client": "gtx",
            "sl": "auto",
            "tl": norm,
            "dt": "t",
            "q": text,
        })
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=3) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            if data and data[0]:
                translated = "".join([part[0] for part in data[0] if part and part[0]])
                if translated:
                    return translated
    except Exception:
        pass
    return text


def translate_phrase(text: str, lang: str = "en") -> str:
    """Translate standard notification phrases, button labels, and table keys if matched, falling back to auto-translate."""
    if not text:
        return text
    norm = normalize_language(lang)
    if norm == "en":
        return text
    lang_dict = TRANSLATIONS.get(norm, {})
    # 1. Exact phrase match in pre-translated dictionary
    if text in lang_dict:
        return lang_dict[text]
    # 2. Key variation, e.g. "Open your account" -> "open_account"
    snake = text.lower().replace(" ", "_").replace("—", "").strip()
    if snake in lang_dict:
        return lang_dict[snake]
    if f"{snake}_cta" in lang_dict:
        return lang_dict[f"{snake}_cta"]
    if f"{snake}_title" in lang_dict:
        return lang_dict[f"{snake}_title"]
    # 3. Dynamic / custom sentence translation with graceful fallback
    return auto_translate_text(text, norm)

